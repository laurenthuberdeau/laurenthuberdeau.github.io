#!/usr/bin/env node
/* Build index.html from src/.

   The page is four sources — src/index.html (markup), src/app.css, src/app.js and
   src/scenarios.js — combined into one self-contained file, because the artifact is meant to be
   opened straight from disk and shared as a single file with no server and no build step at
   read time.

     node tools/build.mjs           write index.html
     node tools/build.mjs --check   exit 1 if index.html is not what src/ says it should be

   Sources are joined at marker lines, not by concatenating whole files, so the built file keeps
   the byte-for-byte shape it had before the split: 'use strict' stays the first statement of the
   script, and the corpus sits where it always sat. The markers are the only wiring. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'index.html');
const BANNER = '<!-- Generated by tools/build.mjs from src/. Edit src/, then run:\n'
             + '         node tools/build.mjs — hand edits to this file are overwritten. -->\n';

/* every injection point in the built file, in document order */
const SOURCES = [
  ['src/index.html', '/* inject:css */', 'src/app.css'],
  ['src/index.html', '/* inject:app */', 'src/app.js'],
];

const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');

/* replace one marker LINE with a file's contents: the marker's own newline is consumed by the
   payload's trailing newline, so nothing about the surrounding text shifts */
function inject(text, marker, payload, where) {
  const needle = marker + '\n';
  const at = text.indexOf(needle);
  if (at < 0) throw new Error('marker ' + marker + ' missing from ' + where);
  if (text.indexOf(needle, at + 1) >= 0) throw new Error(marker + ' appears twice in ' + where);
  return text.slice(0, at) + payload + text.slice(at + needle.length);
}

export function build() {
  /* the app script injects the corpus into itself, so build the scripts before the document */
  const app = inject(read('src/app.js'), '/* inject:scenarios */', read('src/scenarios.js'), 'src/app.js');
  let out = read('src/index.html');
  out = inject(out, '/* inject:css */', read('src/app.css'), 'src/index.html');
  out = inject(out, '/* inject:app */', app, 'src/index.html');
  return BANNER + out;
}

/* Only run the CLI when invoked directly, so the selftest can import build() to verify the
   artifact without triggering a rebuild or a --check exit. */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  if (args.includes('--check')) {
    const want = build();
    const have = fs.existsSync(OUT) ? read('index.html') : '';
    if (have === want) {
      console.log('index.html is current');
    } else {
      console.error('index.html is STALE — it does not match src/.');
      console.error('Edit src/ and run: node tools/build.mjs');
      process.exit(1);
    }
  } else {
    const out = build();
    fs.writeFileSync(OUT, out);
    console.log('wrote index.html  ' + out.split('\n').length + ' lines  from src/{index.html,app.css,app.js,scenarios.js}');
  }
}

export { OUT };
